"""Manifest of EVERY task in a dataset, annotated with its DAG-rule eligibility.

    python scripts/build_manifest_all.py --data data/final_test \
        --manifest scripts/nscc/tasks_all_final_test.manifest

scripts/build_eligibility.py emits only the tasks that CAN exhibit a DAG-fixable
precondition failure, because that was the pre-registered run set. This emits all
of them, carrying the same tags as an annotation instead of as a filter, so the
ineligible tasks can be run as a negative control: the check is supposed to stay
silent on those, and that only means something if they were actually run.

Tag derivation is imported from build_eligibility, not reimplemented, so the two
manifests cannot drift apart. A task with no tags is ineligible by exactly the
same rule that would have excluded it there.
"""
import argparse
import glob
import os
import sys
from collections import Counter

sys.path.append(".")
from scripts.build_eligibility import load_rows, scene, tags_for, floor_of


def tier_of(path):
    """The dataset's difficulty tier, read from the filename as run_kg_task does."""
    b = os.path.basename(path)
    return ("vague" if "vague" in b else "complex" if "pddl" in b else "easy")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data/final_test")
    ap.add_argument("--manifest", default="scripts/nscc/tasks_all_final_test.manifest")
    ap.add_argument("--label", default="MAT-THOR")
    args = ap.parse_args()

    rows, tags_out = [], []
    counts, tiers, n_elig, no_fixture = Counter(), Counter(), 0, set()

    for path in sorted(glob.glob(os.path.join(args.data, "*.json"))):
        floor = floor_of(path)
        objs = scene(floor)
        if objs is None:
            no_fixture.add(floor)
            continue
        for idx, row in enumerate(load_rows(path)):
            if row.get("_bad"):
                continue
            tags = tags_for(row, objs)
            tier = tier_of(path)
            counts.update(tags or ["NONE_ineligible"])
            tiers.update([tier])
            n_elig += bool(tags)
            rows.append("%s | %s | %s" % (floor, idx, path))
            tags_out.append("%s|%s|%s|%s|%s|%s"
                            % (floor, idx, os.path.basename(path), tier,
                               ",".join(tags) or "-", row.get("task", "").strip()))

    hdr = [
        "# EVERY %s task, eligible or not. Generated by" % args.label,
        "# scripts/build_manifest_all.py from scene metadata and the dataset's",
        "# declared goals only - no model output is consulted, so this set is",
        "# fixed before any run and cannot be shaped by what the pipeline",
        "# produced. Tasks with no rule tag are the negative control: the",
        "# Safety-DAG is supposed to derive no violated edge for them.",
        "# Re-derive with:",
        "#   python scripts/build_manifest_all.py --data %s --manifest %s"
        % (args.data, args.manifest),
        "# Per-task tier and rule tags live alongside this file in .tags",
        "# floor | task-index | dataset",
    ]
    open(args.manifest, "w").write("\n".join(hdr + rows) + "\n")
    tagf = os.path.splitext(args.manifest)[0] + ".tags"
    open(tagf, "w").write(
        "# floor|index|dataset|tier|rules|task\n" + "\n".join(tags_out) + "\n")

    print("dataset   : %s (%s)" % (args.data, args.label))
    print("tasks     : %d   eligible %d   ineligible %d"
          % (len(rows), n_elig, len(rows) - n_elig))
    for k, v in counts.most_common():
        print("   %-24s %d" % (k, v))
    print("tiers     : %s" % dict(tiers))
    if no_fixture:
        print("no fixture for floor plans: %s" % sorted(no_fixture))
    print("\nwrote %s\nwrote %s" % (args.manifest, tagf))


if __name__ == "__main__":
    main()
