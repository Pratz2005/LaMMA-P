"""Write the evidence pack: one file per silent-failure case, plus the fix.

    pixi run python scripts/make_evidence.py --out evidence

Every line of every file is read from the run directory or produced by running
Fast Downward on the saved problem file. Nothing is transcribed by hand, so the
pack can be regenerated after any pipeline change and cannot drift from what
the runs actually contain.
"""
import argparse, json, os, re, subprocess, sys, tempfile
sys.path.append(".")
from scripts.safety_dag import derive_dag, check_plan, load_problem, load_graph
from scripts.dag_llm_init import llm_repair_atoms

FD = "./downward/fast-downward.py"
# Overridable so a run can pin the domain it was designed against without
# editing the working tree. Default unchanged.
DOMAIN = os.environ.get("KGLAMP_DOMAIN", "resources/robot3.pddl")
W = 78

# the six runs where the model dropped a state fact and the planner produced a
# confident wrong plan; container is the receptacle the DAG rule fires on
CASES = [
    ("runs_3/FP15_t0_easy_20260902-182953",     "fridge_1",  "apple_fridge_easy"),
    ("runs_3/FP15_t0_complex_20260902-183038",  "fridge_1",  "apple_fridge_complex"),
    ("runs_3/FP15_t9_complex_20260902-184336",  "fridge_1",  "potato_fridge"),
    ("runs_3/FP201_t0_easy_20260902-192327",    "drawer_1",  "watch_drawer"),
    ("runs_3/FP201_t0_complex_20260902-192508", "drawer_1",  "watch_drawer_complex"),
    ("runs_3/FP414_t1_easy_20260902-193004",    "cabinet_1", "plunger_cabinet"),
]

# Cases whose :init repair is produced by the model rather than written in by
# the injector. The DAG still does the detecting - it is what notices a plan the
# planner called solved - but the atom comes back from a prompt, is screened
# against the domain and the graph, and is injected only if it survives. Kept to
# one case on purpose: the other five are the deterministic control it is
# measured against, and both arms have to be in the same pack to be comparable.
LLM_REPAIR = {"watch_drawer"}


def rule(t="", ch="="):
    return ch * W + ("\n" + t + "\n" + ch * W if t else "")


def plan(problem_text, timeout=300):
    tmp = tempfile.mkdtemp(prefix="fd_")
    pf = os.path.join(tmp, "p.pddl"); open(pf, "w").write(problem_text)
    try:
        cp = subprocess.run(
            [sys.executable, FD, "--plan-file", os.path.join(tmp, "sas_plan"),
             "--sas-file", os.path.join(tmp, "out.sas"),
             "--alias", "lama-first", DOMAIN, pf],
            capture_output=True, text=True, timeout=timeout)
        log = cp.stdout + cp.stderr
    except subprocess.TimeoutExpired:
        return [], "TIMEOUT"
    acts = []
    for c in (os.path.join(tmp, "sas_plan"), os.path.join(tmp, "sas_plan.1")):
        if os.path.exists(c):
            acts = [l.strip() for l in open(c) if l.strip().startswith("(")]
            break
    return acts, log


def inject(pddl, atoms):
    m = re.search(r"\(:init\b", pddl)
    low = pddl.lower()
    add = [a for a in atoms
           if not re.search(re.escape(a.lower()).replace(r"\ ", r"\s+"), low)]
    if not add:
        return pddl, []
    return pddl[:m.end()] + "\n" + "\n".join("    " + a for a in add) + pddl[m.end():], add


def section(d, container):
    """The shared narrative: graph -> prompt -> output -> PDDL -> wrong plan."""
    rep = json.load(open(os.path.join(d, "report.json")))
    tri = json.load(open(os.path.join(d, "triplets.json")))
    prop = tri["property"]
    base = container.rsplit("_", 1)[0]
    L = []

    L.append(rule("1.  TASK"))
    L.append("task     : %s" % rep["task"])
    L.append("scene    : AI2-THOR FloorPlan%s" % rep["floor_plan"])
    L.append("model    : %s   temperature %s  seed 0"
             % (rep["model"], rep.get("temperature")))
    L.append("run       : %s" % d)
    L.append("\nground truth the task must reach:")
    for g in rep.get("ground_truth_object_states") or []:
        L.append("   %-14s state=%-8s contains=%s"
                 % (g.get("name"), g.get("state"), g.get("contains")))

    L.append("\n" + rule("2.  KNOWLEDGE GRAPH   (built mechanically from AI2-THOR metadata)"))
    L.append("The graph is not generated by the model. These facts are read straight")
    L.append("from the simulator's own object metadata:\n")
    for t in prop:
        if len(t) == 3 and str(t[0]).lower().startswith(base):
            if (t[1] == "has_capability" and t[2] == "openable") or t[1] == "isOpen":
                L.append("   (%s, %s, %s)" % (t[0], t[1], t[2]))
    L.append("\nSo %s CAN be opened, and is CLOSED right now." % container)

    L.append("\n" + rule("3.  WHAT THE MODEL WAS TOLD   (stage 3 prompt, Eq. 4)"))
    pp = os.path.join(d, "3_property.prompt.txt")
    if os.path.exists(pp):
        for i, line in enumerate(open(pp), 1):
            if re.search(r"isClosed\s+%s" % base, line, re.I):
                L.append("   line %-4d %s" % (i, line.strip()))
    L.append("\nThe fact was in the prompt.")

    L.append("\n" + rule("4.  WHAT THE MODEL RETURNED   (stage 3 output)"))
    po = os.path.join(d, "3_property.out.txt")
    kept = [l.strip() for l in open(po) if re.search(base, l, re.I)] if os.path.exists(po) else []
    for l in kept:
        L.append("   " + l)
    if not any(re.search(r"isClosed", l, re.I) for l in kept):
        L.append("\n   >>> (isClosed %s) is ABSENT. The capability was kept," % base.title())
        L.append("   >>> the STATE was dropped.")

    pddl = load_problem(d)
    L.append("\n" + rule("5.  THE GENERATED PROBLEM PDDL   (what the planner was given)"))
    init = pddl[pddl.find("(:init"):pddl.find("(:goal")]
    L.append(init.rstrip())
    L.append("\n(:goal")
    g = pddl[pddl.find("(:goal"):]
    L.append("\n".join(g.splitlines()[1:6]))
    L.append("\n   >>> no (object-close %s) anywhere in :init" % container)

    acts, log = plan(pddl)
    L.append("\n" + rule("6.  THE PLAN FAST DOWNWARD PRODUCED"))
    L.append("planner: %s" % ("Solution found" if "Solution found" in log else "no plan"))
    for a in acts:
        mark = "   <-- puts into a CLOSED %s" % base if a.lower().startswith("(putobject") and container in a.lower() else ""
        L.append("   %s%s" % (a, mark))
    L.append("\n   >>> %d actions, and NOT ONE of them is OpenObject."
             % len(acts))

    L.append("\n" + rule("7.  WHY THIS HAPPENS"))
    L.append("""PutObject's last precondition is:

    (not (object-close ?location))

PDDL uses the closed-world assumption: a fact not written in :init is FALSE.
So the planner reasons:

    is (object-close %s) in :init?   no
    therefore it is                    false
    therefore (not (object-close ...)) true
    therefore PutObject is             ALLOWED

The precondition passes, so there is no reason to open anything, and opening
costs an extra step that a shortest-path planner will avoid. Because the rule
is phrased as "not closed", SAYING NOTHING has the same effect as saying the
container is open. Silence grants permission.

Fast Downward is not confused and did not make a mistake. It correctly solved
the problem it was handed. The problem it was handed was wrong about the world.""" % container)

    L.append("\n" + rule("8.  WHY THIS IS THE DANGEROUS CASE"))
    L.append("""The planner reports SUCCESS. The plan is executable. Every action is legal.
Nothing in the symbolic pipeline signals a problem. But the robot walks up to
a shut %s and lets go of the object.

KGLAMP's replanning loop (Alg. 1) is gated on an error signal e - no plan,
violated precondition, or missing object. Here e is empty, so the loop never
fires. This failure is invisible to the recovery mechanism designed for it.""" % base)
    return "\n".join(L), pddl, acts, rep


def dag_atoms(d, viols):
    """What the injector writes: the violation's own atom, plus its release.

    (object-close Y) blocks PutObject until Y is opened, but OpenObject needs
    (openable Y) as a positive precondition - so injecting the closed state into
    a file whose affordance the model dropped seals the container and turns a
    wrong plan into no plan. Both facts come from the same graph.
    """
    g = load_graph(d)
    atoms = set(v.edge.atom_init for v in viols)
    for a in list(atoms):
        m = re.match(r"\(object-close\s+([^\s()]+)\)", a)
        if m and m.group(1) in g.openable:
            atoms.add("(openable %s)" % m.group(1))
    return sorted(atoms)


def deterministic_repair_section(added, container, base):
    """Section 10, injector arm: the DAG already holds the atom, so it writes it."""
    F = [rule("10. DETERMINISTIC REPAIR   (no language model)"),
         """The DAG derived the missing fact from the graph, so it already HOLDS the
atom. It does not need to ask a model to produce it - it writes it in:
"""]
    for a in added:
        F.append("   + %s      -> :init" % a)
    note = ["", "(object-close %s) is the state fact the model dropped." % container]
    if any("openable" in a for a in added):
        note += ["(openable %s) is its release, and was missing too: a brake with no"
                 % container,
                 "way to lift it seals the %s permanently and turns a wrong plan" % base,
                 "into no plan at all. Both come from the same graph."]
    else:
        note += ["(openable %s) was already present in this file, so only the state"
                 % container,
                 "fact had to be restored. Where a run drops BOTH, the injector adds the",
                 "affordance as well - a brake with no way to lift it would seal the",
                 "%s permanently and turn a wrong plan into no plan at all." % base]
    note += ["", "Nothing else is touched. Not the goal, not the objects, not any other fact."]
    F.append("\n".join(note))
    return "\n".join(F)


def llm_repair_section(r, added, container, base):
    """Section 10, model arm: the prompt, the reply, the screen, the comparison.

    The whole prompt goes in the file. The claim being made here is that a model
    can restore the fact when it is asked for the fact - which is only worth
    anything if the reader can see exactly what it was asked, and check that the
    answer was not in the question.
    """
    F = [rule("10. LLM REPAIR   (the atom is produced by the model)"),
         """The other cases in this pack repair the file deterministically: the DAG
derived the ordering constraint from the graph, so it already holds the atom
and writes it in. This case does not write it in. The DAG detects - it is still
what notices a plan the planner called solved - and then the missing fact is
asked for.

The model is asked for a FACT. Not for a plan, not for a repair strategy, not
for a rewritten problem file: for the ground atoms that belong in (:init ...)
and are not there. It is shown the violation, the knowledge-graph triplets for
the entities that violation names, the (:init ...) the planner was given, and
the domain's predicate vocabulary with a translation table. It is not shown the
answer: the graph facts appear in the graph's notation, not pre-rendered as the
PDDL atoms it is supposed to emit, and the worked example is a different scene
with a different container.

model: %s

--- THE PROMPT %s
%s
--- THE MODEL'S REPLY %s
%s

--- SCREENING %s
Three passes stand between that reply and the problem file. A model that
answers in the property stage's vocabulary, or names an object the file does
not declare, or asserts something the graph does not - each of those would
otherwise be written straight into :init, and the first two would be dropped by
Fast Downward without an error, so the repair would appear to happen and change
nothing.

  1. syntax      one balanced (predicate arg ...) per line; prose discarded
  2. vocabulary  predicate declared by the domain, arguments declared by the
                 problem file
  3. truth       the atom must be one the knowledge graph asserts
""" % (r.model,
        "-" * max(0, W - 15),
        r.prompt.rstrip(),
        "-" * max(0, W - 22),
        r.raw.rstrip() or "(empty)",
        "-" * max(0, W - 14))]

    for a in r.screened.accepted:
        F.append("   accepted  + %s      -> :init" % a)
    for a, why in r.screened.redundant:
        F.append("   already   = %-28s %s" % (a, why))
    for a, why in r.screened.rejected:
        F.append("   REJECTED  x %-28s %s" % (a, why))
    if not (r.screened.accepted or r.screened.redundant or r.screened.rejected):
        F.append("   the reply contained no parseable atom.")

    F.append("\n--- AGAINST THE DETERMINISTIC REPAIR " + "-" * max(0, W - 37))
    F.append("""The injector, on this same violation, would have written:

   %s

   model agreed with : %s
   model missed      : %s
   model added extra : %s

Only the third pass can tell the difference between the two atoms that clear
this violation. (object-close %s) is true and (object-open %s) is
false, and both satisfy PutObject's precondition well enough for the planner to
stop complaining - the second one by making the wrong plan legal instead of
making the world right. The graph decides which is which; the model does not.

Nothing else is touched. Not the goal, not the objects, not any other fact.""" %
             (", ".join(r.dag_atoms) or "(nothing)",
              ", ".join(r.agreed) or "NOTHING",
              ", ".join(r.missed) or "nothing",
              ", ".join(r.extra) or "nothing",
              container, container))
    return "\n".join(F)


def fix_sections(d, container, body, pddl, acts, rep, use_llm=False):
    """Sections 9-12: DAG check, repair, replan, result. Returns (text, ok, ...).

    The repair is either written in by the injector or asked of the model; the
    detection, the injection mechanics, the replan and the re-check are the same
    either way, so the two arms differ only in where `atoms` comes from and in
    what section 10 has to show for it.
    """
    base = container.rsplit("_", 1)[0]
    edges = derive_dag(d)
    viols = check_plan(edges, [a.lower() for a in acts], pddl)

    repair = None
    if use_llm:
        repair = llm_repair_atoms(d, viols, pddl, rep["task"], log_dir=d)
        atoms = list(repair.screened.accepted)
    else:
        atoms = dag_atoms(d, viols)
    fixed, added = inject(pddl, sorted(atoms))
    acts2, log2 = plan(fixed)
    viols2 = check_plan(edges, [a.lower() for a in acts2], fixed)
    solved2 = "Solution found" in log2

    F = [body, "\n" + rule("9.  SAFETY-DAG CHECK   (reads the GRAPH, not the PDDL)")]
    F.append("""The check does not look at the generated problem file - that is the thing
that is wrong. It derives what MUST be true from the knowledge graph:

    IF the goal is (X in Y)
    AND (Y, has_capability, openable)
    AND (Y, isOpen, False)
    THEN Open(Y) must come before Put(X, Y)

That is a rule over graph facts, so it holds whether or not the model
remembered to write the fact down.
""")
    fmt = lambda t: "%s(%s)" % (t[0], ", ".join(t[1:])) if t else "*"
    F.append("   derived %d ordering edge(s):" % len(edges))
    for e in edges:
        F.append("      %s  <  %s      [%s]" % (fmt(e.before), fmt(e.after), e.rule))
    F.append("\n   violations found: %d" % len(viols))
    for v in viols:
        F.append("      %s: required %s before %s"
                 % (v.reason, fmt(v.edge.before), fmt(v.edge.after)))
    F.append("\n   The check runs regardless of planner success, so it sees a failure")
    F.append("   that reported 'Solution found'.")

    F.append("\n" + (llm_repair_section(repair, added, container, base) if use_llm
                     else deterministic_repair_section(added, container, base)))

    F.append("\n" + rule("11. REPLAN WITH THE FACT RESTORED" if added else
                         "11. REPLAN WITH NOTHING RESTORED"))
    F.append("planner: %s" % ("Solution found" if solved2 else "no plan"))
    for a in acts2:
        F.append("   %s%s" % (a, "   <-- INSERTED BY THE PLANNER"
                              if a.lower().startswith("(openobject") else ""))
    F.append(("""
We did not tell it to open the %s. We said the %s is shut. With
(object-close %s) true, PutObject's precondition fails, and OpenObject's
effect deletes that fact - so the only route to the goal now runs through
opening it. The planner rediscovered the ordering by itself.""" % (base, base, container))
             if added else ("""
Nothing survived screening, so :init is unchanged and this is the same plan as
section 6 - the same silent failure, replanned. The %s is still shut and the
robot still lets go of the object in front of it. Screening did not cause this;
it refused to write a fact the model did not supply, which is the only thing it
can do without becoming the injector.""" % base))

    ok = solved2 and not viols2
    F.append("\n" + rule("12. RESULT"))
    F.append("""   plan before repair : %d actions, 0 of them OpenObject
   plan after  repair : %d actions, %s
   DAG violations     : %d  ->  %d
   atoms injected     : %s
   model calls used in the repair : %d

%s"""
             % (len(acts), len(acts2),
                "opens the %s first" % base if ok else "still not opening the %s" % base,
                len(viols), len(viols2), ", ".join(added) or "none",
                1 if use_llm else 0,
                "The task is now actually accomplished." if ok else
                "The violation survives. The repair is not backed up by the injector "
                "on this\ncase - a model that does not return the fact returns no "
                "repair, and that is\nthe measurement, not a failure to route around."))
    return "\n".join(F), ok, len(acts), len(acts2), len(viols), len(viols2)


def preflight_llm():
    """Fail before writing anything if the model server is not reachable.

    The LLM arm needs a live endpoint. Discovering that halfway through leaves
    five fresh case files beside a stale README, so the check happens first and
    the pack is either regenerated whole or not at all.
    """
    from scripts.pddlrun_llmseparate import LLMHandler
    llm = LLMHandler()
    try:
        [m.id for m in llm.client.models.list().data]
    except Exception as exc:
        sys.exit("\ncannot reach the model server at %s: %s\n"
                 "The LLM repair arm (%s) needs it. Start vllm serve, set\n"
                 "KGLAMP_LLM_BASE_URL, or pass --no-llm to build the pack with the\n"
                 "deterministic injector on every case."
                 % (llm.base_url, exc, ", ".join(sorted(LLM_REPAIR))))
    return llm.model


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="evidence")
    ap.add_argument("--no-llm", action="store_true",
                    help="repair every case with the injector, including the "
                         "ones in LLM_REPAIR; needs no model server")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    index = []

    llm_cases = set() if args.no_llm else LLM_REPAIR
    if llm_cases:
        print("LLM repair arm: %s (model %s)"
              % (", ".join(sorted(llm_cases)), preflight_llm()))

    for n, (d, container, slug) in enumerate(CASES, 1):
        body, pddl, acts, rep = section(d, container)
        fp, tier = rep["floor_plan"], ("easy" if "_easy_" in d else
                                       "complex" if "_complex_" in d else "vague")
        stem = "%02d_FP%s_t%s_%s_%s" % (n, fp, rep["task_index"], tier,
                                        container.rsplit("_", 1)[0])
        head = rule("SILENT FAILURE %d of %d   -   a plan the planner accepts, and the "
                    "task is not done" % (n, len(CASES))) + "\n\n"
        open(os.path.join(args.out, stem + ".txt"), "w").write(head + body + "\n")
        print("wrote", stem + ".txt")

        use_llm = slug in llm_cases
        ftxt, ok, s0, s1, v0, v1 = fix_sections(d, container, body, pddl, acts,
                                                rep, use_llm=use_llm)
        fname = "FIX_%s.txt" % slug
        fhead = rule("SAFETY-DAG FIX   -   '%s'%s"
                     % (rep["task"], "   [LLM repair]" if use_llm else "")) + "\n\n"
        open(os.path.join(args.out, fname), "w").write(fhead + ftxt + "\n")
        print("wrote", fname, "(repaired)" if ok else "(NOT repaired)",
              "[LLM]" if use_llm else "")
        index.append((stem + ".txt", fname, rep["task"], container, s0, s1, v0, v1,
                      ok, use_llm))

    R = ["# Evidence pack\n",
         "Qwen2-7B-Instruct, temperature 0, seed 0. Generated by",
         "`scripts/make_evidence.py` from the run directories; every plan is",
         "produced by running Fast Downward on the saved problem file, so the",
         "pack can be regenerated after any pipeline change and cannot drift.\n",
         "## The problem\n",
         "In each case the knowledge graph says a container is openable and",
         "currently closed, the model was shown that fact, and its problem file",
         "omitted it. The planner then produced a plan that puts an object into a",
         "shut container - and reported success.\n",
         "## The fix\n",
         "Each `FIX_*.txt` continues the same case through the Safety-DAG: ordering",
         "edges derived from the graph rather than from the PDDL, the violation on a",
         "plan the planner called solved, the missing atom restored, replan.\n",
         "The `repair` column says where that atom came from. `injector` is",
         "deterministic - the DAG derived the constraint from the graph, so it",
         "already holds the atom and writes it in, with no model involved. `LLM` is",
         "the same detection and the same injection mechanics, but the atom is asked",
         "for: the prompt is in the FIX file in full, and the reply is screened",
         "against the domain's vocabulary and the graph's facts before anything is",
         "written. One case runs that arm so the two are comparable inside one pack.\n",
         "| problem | fix | task | container | plan | violations | repair |",
         "|---|---|---|---|---|---|---|"]
    for stem, fname, task, cont, s0, s1, v0, v1, ok, use_llm in index:
        R.append("| `%s` | `%s` | %s | %s | %d -> %d actions | %d -> %d | %s |"
                 % (stem, fname, task[:40], cont, s0, s1, v0, v1,
                    "LLM" if use_llm else "injector"))
    done = sum(1 for i in index if i[8])
    R.append("\n%d of %d repaired: violations cleared, and each repaired plan opens"
             % (done, len(index)))
    R.append("the container before putting anything into it.")
    open(os.path.join(args.out, "README.md"), "w").write("\n".join(R) + "\n")
    print("wrote README.md")


if __name__ == "__main__":
    main()
